    def test_validate_cache_integrity(self) -> None:
        """Test cache integrity validation."""
        with tempfile.TemporaryDirectory() as tmpdir:
            node_modules = Path(tmpdir) / "node_modules"
            node_modules.mkdir()

            # Create valid package structure
            react_pkg = node_modules / "react"
            react_pkg.mkdir()
