            node_modules.mkdir()

            # Create corrupt package (no package.json)
            corrupt_pkg = node_modules / "corrupt_package"
            corrupt_pkg.mkdir()
            (corrupt_pkg / "README.md").write_text("Missing package.json!")

            # Validate
            is_corrupt = not (corrupt_pkg / "package.json").exists()

            assert is_corrupt, "Should detect corrupt package"

